// Gera supabase/seeds/001_distribuidora_exemplo.sql a partir do catálogo
// fictício (test/apoio/catalogo-exemplo.ts). As medidas de cada produto saem dos
// moldes da organização, como no sync de verdade.
//
//   node --experimental-strip-types app/scripts/gerar-seed-exemplo.mjs

import { writeFileSync } from 'node:fs';
import { register } from 'node:module';

register('../test/resolve-hook.mts', import.meta.url);
const { PRODUTOS_EXEMPLO, ORG_EXEMPLO } = await import('../test/apoio/catalogo-exemplo.ts');
const { lerMedidas } = await import('../src/lib/catalogo/moldes.ts');

const q = valor => (valor === null || valor === undefined ? 'NULL' : `'${String(valor).replace(/'/g, "''")}'`);
const json = valor => (valor === null ? 'NULL' : `${q(JSON.stringify(valor))}::jsonb`);

const grupos = [...new Set(PRODUTOS_EXEMPLO.map(p => p.grupo))];
const idDoGrupo = g => `e8e00000-0000-4000-8001-${String(grupos.indexOf(g) + 1).padStart(12, '0')}`;

const linhas = [
  '-- Demo seed: Distribuidora Exemplo, a fictional B2B steel distributor.',
  '-- Generated by app/scripts/gerar-seed-exemplo.mjs from app/test/apoio/catalogo-exemplo.ts. Do not edit by hand.',
  '-- Local Supabase only. The ERP integration points at the fictional ERP (app/scripts/simulador-erp.mjs).',
  '',
  'BEGIN;',
  '',
  `DELETE FROM public.catalogo_produtos WHERE organization_id = ${q(ORG_EXEMPLO)};`,
  `DELETE FROM public.catalogo_grupos WHERE organization_id = ${q(ORG_EXEMPLO)};`,
  `DELETE FROM public.erp_regioes WHERE organization_id = ${q(ORG_EXEMPLO)};`,
  `DELETE FROM public.organization_integrations WHERE organization_id = ${q(ORG_EXEMPLO)};`,
  '',
  `INSERT INTO public.organizations (id, nome, nome_fantasia, segmento, descricao, produtos)
VALUES (${q(ORG_EXEMPLO)}, 'Distribuidora Exemplo Ltda', 'Distribuidora Exemplo', 'distribuidora',
  'Distribuidora fictícia de aço e materiais de serralheria, usada na demo.', ARRAY['vendas'])
ON CONFLICT (id) DO UPDATE SET nome = EXCLUDED.nome, nome_fantasia = EXCLUDED.nome_fantasia, produtos = EXCLUDED.produtos;`,
  '',
  'INSERT INTO public.catalogo_grupos (id, organization_id, codigo, nome) VALUES',
  grupos.map((g, i) => `  (${q(idDoGrupo(g))}, ${q(ORG_EXEMPLO)}, ${q(String(4101 + i))}, ${q(g)})`).join(',\n') + ';',
  '',
  'INSERT INTO public.catalogo_produtos (organization_id, grupo_id, codigo, descricao, unidade, preco, dados, molde, medidas) VALUES',
  PRODUTOS_EXEMPLO.map(p => {
    const { molde, medidas } = lerMedidas(ORG_EXEMPLO, p.grupo, p.descricao);
    const dados = p.peso_kg === null ? {} : { peso_kg: String(p.peso_kg) };
    return `  (${q(ORG_EXEMPLO)}, ${q(idDoGrupo(p.grupo))}, ${q(p.codigo)}, ${q(p.descricao)}, ${q(p.unidade)}, ${p.preco}, ${json(dados)}, ${q(molde)}, ${json(medidas)})`;
  }).join(',\n') + ';',
  '',
  'INSERT INTO public.erp_regioes (organization_id, regiao_id, nome, cidades) VALUES',
  `  (${q(ORG_EXEMPLO)}, '001', 'CENTRO', ${json([{ cidade: 'JUNDIAÍ', uf: 'SP' }, { cidade: 'ITATIBA', uf: 'SP' }, { cidade: 'LOUVEIRA', uf: 'SP' }])}),`,
  `  (${q(ORG_EXEMPLO)}, '002', 'NORTE', ${json([{ cidade: 'ITUPEVA', uf: 'SP' }, { cidade: 'JARINU', uf: 'SP' }])});`,
  '',
  '-- The API key of the fictional ERP is saved from the panel (Desenvolvimento > ERP), which stores it in Vault.',
  'INSERT INTO public.organization_integrations (organization_id, tipo, endereco_base, ativo, config) VALUES',
  `  (${q(ORG_EXEMPLO)}, 'erp', 'http://localhost:4000', true, '{}'::jsonb);`,
  '',
  'COMMIT;',
  '',
];

const destino = new URL('../../supabase/seeds/001_distribuidora_exemplo.sql', import.meta.url);
writeFileSync(destino, linhas.join('\n'));
console.log(`${grupos.length} grupos, ${PRODUTOS_EXEMPLO.length} produtos → ${destino.pathname}`);
